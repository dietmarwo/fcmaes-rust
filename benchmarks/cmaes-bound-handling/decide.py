#!/usr/bin/env python3
"""Tables and decision of the CMA-ES bound-handling test (PROTOCOL.md, section 4).

Reads the raw files in results/ and writes results/report.md:

- A: results/controller.tsv, budget 110000, seeds 1 to 10
- B: results/truss.tsv (candidate-harness protocol T rows), truss_sizing,
  arms jso_cma (clip), jso_cma_rz (repair), jso_cma_tr (transform), 10 reps
- C: results/messenger.tsv, D: results/cassini2.tsv, seeds 1 to 12
- informational: results/controller-900k.tsv (5 seeds), results/probes.tsv,
  and the evaluations spent in C and D.

Lower is better everywhere. Tests: two-sided Mann-Whitney U (scipy default),
0.05, uncorrected; a NaN p-value counts as 1. "Significantly better" means
p < 0.05 and transform's values tend lower than the other mode's (U of
transform below n1 n2 / 2); "significantly worse" the opposite direction.

Usage: python3 decide.py [--results DIR]
"""

import csv
import math
import statistics
import sys
from pathlib import Path

from scipy.stats import mannwhitneyu

ALPHA = 0.05
MODES = ("clip", "repair", "transform")
HARNESS_ARMS = {"jso_cma": "clip", "jso_cma_rz": "repair", "jso_cma_tr": "transform"}


def rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def by_mode(records, key_mode, key_value, expected_keys, key_id):
    """{mode: [values]} with exactly the expected ids per mode, or an error."""
    out = {m: {} for m in MODES}
    for r in records:
        m = key_mode(r)
        if m not in out:
            continue
        i = key_id(r)
        if i not in expected_keys:
            continue
        if i in out[m]:
            raise SystemExit(f"duplicate row: {m} {i}")
        out[m][i] = float(key_value(r))
    for m in MODES:
        missing = sorted(set(expected_keys) - set(out[m]))
        if missing:
            return None, f"{m}: missing {missing}"
    return {m: [out[m][i] for i in sorted(expected_keys)] for m in MODES}, None


def mwu(x, y):
    """(p, transform_tends_lower) for samples x (transform) and y."""
    res = mannwhitneyu(x, y)  # scipy defaults: two-sided, method "auto"
    p = float(res.pvalue)
    if math.isnan(p):
        p = 1.0
    lower = float(res.statistic) < len(x) * len(y) / 2.0
    return p, lower


def summary(values):
    return statistics.median(values), min(values), max(values)


def compare(data):
    """Medians and the two tests of transform against clip and repair."""
    out = {m: summary(data[m]) for m in MODES}
    p_clip, lower_clip = mwu(data["transform"], data["clip"])
    p_rep, lower_rep = mwu(data["transform"], data["repair"])
    return out, (p_clip, lower_clip), (p_rep, lower_rep)


def fmt(v):
    return f"{v:.6g}"


def main():
    args = sys.argv[1:]
    results = Path(__file__).resolve().parent / "results"
    if "--results" in args:
        results = Path(args[args.index("--results") + 1])
    lines = ["# CMA-ES bound handling: report", "",
             "Generated by `decide.py` from the raw files in this directory. "
             "Lower is better. p: two-sided Mann-Whitney U (scipy default).", ""]
    comps = {}
    problems = []

    # A
    try:
        a = rows(results / "controller.tsv")
        data, err = by_mode([r for r in a if r["budget"] == "110000"], lambda r: r["mode"],
                            lambda r: r["loss"], set(range(1, 11)), lambda r: int(r["seed"]))
    except FileNotFoundError:
        data, err = None, "controller.tsv missing"
    comps["A"] = (data, err)

    # B
    try:
        b = [r for r in rows(results / "truss.tsv") if r["problem"] == "truss_sizing"]
        for r in b:
            if (r["root_seed"], r["total"], r["run_cap"]) != ("7", "1000000", "1000000"):
                raise SystemExit(f"truss.tsv: unexpected settings in {r}")
        data, err = by_mode(b, lambda r: HARNESS_ARMS.get(r["solver"]), lambda r: r["best_value"],
                            set(range(10)), lambda r: int(r["rep"]))
    except FileNotFoundError:
        data, err = None, "truss.tsv missing"
    comps["B"] = (data, err)

    # C and D
    evals = {}
    for cid, name in (("C", "messenger"), ("D", "cassini2")):
        try:
            c = rows(results / f"{name}.tsv")
            data, err = by_mode(c, lambda r: r["mode"], lambda r: r["value"],
                                set(range(1, 13)), lambda r: int(r["seed"]))
            ev, _ = by_mode(c, lambda r: r["mode"], lambda r: r["evaluations"],
                            set(range(1, 13)), lambda r: int(r["seed"]))
            rt, _ = by_mode(c, lambda r: r["mode"], lambda r: r["retries"],
                            set(range(1, 13)), lambda r: int(r["seed"]))
            evals[cid] = (ev, rt)
        except FileNotFoundError:
            data, err = None, f"{name}.tsv missing"
        comps[cid] = (data, err)

    titles = {
        "A": "A: neural controller, plain CMA-ES, 110,000 evaluations, seeds 1-10",
        "B": "B: truss_sizing, jSO->CMA, protocol T, 1,000,000 evaluations, root seed 7, 10 reps",
        "C": "C: Messenger (reduced), coordinated DE->CMA retry, seeds 1-12",
        "D": "D: Cassini2, coordinated DE->CMA retry, seeds 1-12",
    }
    stats = {}
    for cid in "ABCD":
        data, err = comps[cid]
        lines += [f"## {titles[cid]}", ""]
        if data is None:
            lines += [f"Incomplete: {err}.", ""]
            problems.append(cid)
            continue
        s, (pc, lc), (pr, lr) = compare(data)
        stats[cid] = (s, (pc, lc), (pr, lr))
        lines += ["| mode | median | best | worst |", "|---|---:|---:|---:|"]
        for m in MODES:
            med, best, worst = s[m]
            lines.append(f"| {m} | {fmt(med)} | {fmt(best)} | {fmt(worst)} |")
        lines += ["",
                  f"- transform vs clip: p = {pc:.4g}, transform tends "
                  f"{'lower' if lc else 'higher'}; "
                  + ("significantly better" if pc < ALPHA and lc else
                     "significantly worse" if pc < ALPHA else "no significant difference"),
                  f"- transform vs repair: p = {pr:.4g}, transform tends "
                  f"{'lower' if lr else 'higher'}; "
                  + ("significantly better" if pr < ALPHA and lr else
                     "significantly worse" if pr < ALPHA else "no significant difference"),
                  ""]
        if cid in evals and evals[cid][0] is not None:
            ev, rt = evals[cid]
            lines += ["Evaluations spent and retries (informational):", "",
                      "| mode | evaluations, sum | evaluations, median | retries, median |",
                      "|---|---:|---:|---:|"]
            for m in MODES:
                lines.append(f"| {m} | {int(sum(ev[m]))} | {fmt(statistics.median(ev[m]))} | "
                             f"{fmt(statistics.median(rt[m]))} |")
            lines.append("")

    # Decision
    lines += ["## Decision (PROTOCOL.md, section 4)", ""]
    if problems:
        lines += [f"No decision: comparisons {', '.join(problems)} are incomplete.", ""]
        decision = None
    else:
        s_a, (pc, lc), _ = stats["A"]
        med_a = s_a["transform"][0]
        gain = med_a <= 0.2 and pc < ALPHA and lc
        lines += [f"Condition 1, keeps the controller gain: median of transform in A "
                  f"{fmt(med_a)} <= 0.2: {med_a <= 0.2}; significantly better than clip "
                  f"(p = {pc:.4g}): {pc < ALPHA and lc}. Met: {gain}.", ""]
        worse = [c for c in "BCD" if stats[c][2][0] < ALPHA and not stats[c][2][1]]
        better_median = [c for c in "BCD" if stats[c][0]["transform"][0] < stats[c][0]["repair"][0]]
        cond2 = not worse and len(better_median) >= 2
        lines += [f"Condition 2: significantly worse than repair in "
                  f"{', '.join(worse) if worse else 'none'} of B, C, D; median better than "
                  f"repair's in {', '.join(better_median) if better_median else 'none'} "
                  f"({len(better_median)} of 3, at least 2 needed). Met: {cond2}.", ""]
        decision = gain and cond2
        lines += ["**Decision: transform replaces repair as the non-default mode.**" if decision
                  else "**Decision: transform is not merged; repair stays.**",
                  "", "The default stays clip.", ""]
        lines += ["Transform against clip (informational, does not change the default):", ""]
        for c in "ABCD":
            _, (pc, lc), _ = stats[c]
            word = ("significantly better" if pc < ALPHA and lc else
                    "significantly worse" if pc < ALPHA else "no significant difference")
            mt, mc = stats[c][0]["transform"][0], stats[c][0]["clip"][0]
            lines.append(f"- {c}: {word} (p = {pc:.4g}; medians {fmt(mt)} vs {fmt(mc)})")
        lines.append("")

    # Informational
    lines += ["## Informational", ""]
    try:
        big = rows(results / "controller-900k.tsv")
        data, err = by_mode([r for r in big if r["budget"] == "900000"], lambda r: r["mode"],
                            lambda r: r["loss"], set(range(1, 6)), lambda r: int(r["seed"]))
    except FileNotFoundError:
        data, err = None, "controller-900k.tsv missing"
    lines += ["### A at 900,000 evaluations, seeds 1-5", ""]
    if data is None:
        lines += [f"Incomplete: {err}.", ""]
    else:
        lines += ["| mode | median | best | worst |", "|---|---:|---:|---:|"]
        for m in MODES:
            med, best, worst = summary(data[m])
            lines.append(f"| {m} | {fmt(med)} | {fmt(best)} | {fmt(worst)} |")
        lines.append("")
    lines += ["### Boundary-start probes, seeds 1-5 (value, then x)", ""]
    try:
        pr = rows(results / "probes.tsv")
        lines += ["| probe | mode | median value | worst value | median x | evaluations, median |",
                  "|---|---|---:|---:|---:|---:|"]
        for probe in ("quadratic", "damp"):
            for m in MODES:
                sel = [r for r in pr if r["probe"] == probe and r["mode"] == m]
                if len(sel) != 5:
                    lines.append(f"| {probe} | {m} | incomplete ({len(sel)} rows) | | | |")
                    continue
                v = [float(r["value"]) for r in sel]
                x = [float(r["x"]) for r in sel]
                e = [float(r["evaluations"]) for r in sel]
                lines.append(f"| {probe} | {m} | {fmt(statistics.median(v))} | {fmt(max(v))} | "
                             f"{fmt(statistics.median(x))} | {fmt(statistics.median(e))} |")
        lines.append("")
    except FileNotFoundError:
        lines += ["Incomplete: probes.tsv missing.", ""]

    (results / "report.md").write_text("\n".join(lines))
    print("\n".join(lines))
    if decision is not None:
        print(f"DECISION replace_repair={decision}")


if __name__ == "__main__":
    main()
