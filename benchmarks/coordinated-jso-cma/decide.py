#!/usr/bin/env python3
"""Stage-1 decision of the coordinated jSO->CMA protocol.

usage: decide.py [--tsv results/stage1.tsv] [--report results/report.md]
       decide.py --self-test

Two-sided Mann-Whitney U (scipy.stats.mannwhitneyu, default method) per
problem, Holm adjustment over the problems, level 0.05. Lower is better.
A run without a retained result counts as +infinity (worse than every result;
ties among those runs get average ranks).
"""
import argparse, csv, math, os, statistics, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ["cassini1", "cassini2", "rosetta", "tandem", "messenger", "gtoc1", "sagas", "messenger-full"]
ALPHA = 0.05
MARGIN = 1.10


def holm(pvalues):
    """Holm step-down adjusted p-values, in the order of the input."""
    m = len(pvalues)
    idx = sorted(range(m), key=lambda i: pvalues[i])
    adj = [0.0] * m
    running = 0.0
    for rank, i in enumerate(idx):
        running = max(running, min(1.0, (m - rank) * pvalues[i]))
        adj[i] = running
    return adj


def mwu_p(a, b):
    from scipy.stats import mannwhitneyu
    return float(mannwhitneyu(a, b, alternative="two-sided").pvalue)


def analyse(data, pfunc=mwu_p):
    """data: {problem: {"de_cma": [values], "jso_cma": [values], "evals": {arm: [..]}}}"""
    names = [p for p in ORDER if p in data]
    raw = [pfunc(data[p]["de_cma"], data[p]["jso_cma"]) for p in names]
    adj = holm(raw)
    res = {}
    for p, r, h in zip(names, raw, adj):
        d, j = data[p]["de_cma"], data[p]["jso_cma"]
        md, mj = statistics.median(d), statistics.median(j)
        ed, ej = (statistics.median(data[p]["evals"][a]) for a in ("de_cma", "jso_cma"))
        sig = h < ALPHA
        # direction: the arm with the lower median; ties -> lower mean of ranks is not
        # needed because a significant test with equal medians is reported as "tie".
        better = "jso_cma" if mj < md else "de_cma" if md < mj else "tie"
        better_evals, other_evals = (ej, ed) if better == "jso_cma" else (ed, ej)
        res[p] = dict(raw=r, holm=h, med_de=md, med_jso=mj, mean_de=statistics.fmean(d),
                      mean_jso=statistics.fmean(j), best_de=min(d), best_jso=min(j),
                      ev_de=ed, ev_jso=ej, significant=sig, better=better,
                      within_margin=better_evals <= MARGIN * other_evals)
    qual = [p for p in names if res[p]["significant"] and res[p]["better"] == "jso_cma"
            and res[p]["within_margin"]]
    qual_any = [p for p in names if res[p]["significant"] and res[p]["better"] == "jso_cma"]
    return res, names, select_stage2(res, names), qual_any


def select_stage2(res, names):
    """Protocol: problems where jso_cma is significantly better, at most three,
    smallest p first. The 10% margin is applied to the claim, not to the selection."""
    cand = [p for p in names if res[p]["significant"] and res[p]["better"] == "jso_cma"]
    cand.sort(key=lambda p: res[p]["raw"])
    return cand[:3]


def fmt(x):
    if isinstance(x, float):
        if math.isinf(x):
            return "inf"
        return f"{x:.6g}"
    return str(x)


def load(tsv):
    data = {}
    for r in csv.DictReader(open(tsv), delimiter="\t"):
        d = data.setdefault(r["problem"], {"de_cma": [], "jso_cma": [], "evals": {"de_cma": [], "jso_cma": []}, "nr": {"de_cma": 0, "jso_cma": 0}})
        v = float(r["value"]) if r["retained"] == "yes" else math.inf
        d[r["arm"]].append(v)
        d["evals"][r["arm"]].append(int(r["evaluations"]))
        d["nr"][r["arm"]] += r["retained"] == "no"
    return data


def report(data, res, names, stage2):
    L = ["# Stage 1 report", "",
         "Two-sided Mann-Whitney U on the final values, Holm over the eight problems, level 0.05. "
         "Lower values are better. Generated by `decide.py` from `results/stage1.tsv`.", "",
         "| problem | n de/jso | median de_cma | median jso_cma | mean de_cma | mean jso_cma | best de_cma | best jso_cma | p | Holm p | median evals de_cma | median evals jso_cma | better arm (median) | within 10% evals |",
         "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|"]
    for p in names:
        r = res[p]
        L.append("| " + " | ".join([p, f"{len(data[p]['de_cma'])}/{len(data[p]['jso_cma'])}",
                 fmt(r["med_de"]), fmt(r["med_jso"]), fmt(r["mean_de"]), fmt(r["mean_jso"]),
                 fmt(r["best_de"]), fmt(r["best_jso"]), fmt(r["raw"]), fmt(r["holm"]),
                 fmt(r["ev_de"]), fmt(r["ev_jso"]), r["better"], "yes" if r["within_margin"] else "no"]) + " |")
    nr = {p: data[p]["nr"] for p in names if data[p]["nr"]["de_cma"] or data[p]["nr"]["jso_cma"]}
    L += ["", f"Runs without a retained result: {nr if nr else 'none'}.", ""]
    L.append("Problems qualifying for stage 2 (`jso_cma` significantly better, at most three, smallest p first): "
             + (", ".join(stage2) if stage2 else "none") + ".")
    worse = [p for p in names if res[p]["significant"] and res[p]["better"] == "de_cma"]
    L.append("")
    L.append("Problems where `jso_cma` is significantly worse: " + (", ".join(worse) if worse else "none") + ".")
    L.append("")
    L.append("Margin check for the qualifying problems (median evaluations of `jso_cma` at most 10% above `de_cma`): "
             + (", ".join(f"{p}: {'yes' if res[p]['within_margin'] else 'no'}" for p in stage2) if stage2 else "n/a") + ".")
    return "\n".join(L) + "\n"


def self_test():
    # Holm: textbook example
    assert [round(x, 6) for x in holm([0.01, 0.04, 0.03, 0.005])] == [0.03, 0.06, 0.06, 0.02]
    assert holm([0.5]) == [0.5]
    assert holm([0.4, 0.6]) == [0.8, 0.8]
    # stage-2 selection with made-up p-values and a fake test
    pv = {}
    data = {}
    names_p = {"cassini1": 0.0001, "cassini2": 0.9, "rosetta": 0.0002, "tandem": 0.0003,
               "messenger": 0.0004, "gtoc1": 0.0005, "sagas": 0.0006, "messenger-full": 0.0007}
    for p in names_p:
        pv[id(data.setdefault(p, {"de_cma": [2.0] * 3, "jso_cma": [1.0] * 3, "evals": {"de_cma": [100], "jso_cma": [100]}}))] = names_p[p]
    fake = lambda a, b: names_p[next(k for k, v in data.items() if v["de_cma"] is a)]
    res, names, s2, _ = analyse(data, fake)
    # raw p < 0.00625 needed after Holm: smallest 0.0001*8 ok, 0.0002*7, 0.0003*6, ... 0.0007*1
    assert s2 == ["cassini1", "rosetta", "tandem"], s2
    # worse arm is not selected; not significant is not selected
    data["cassini1"]["jso_cma"] = [3.0] * 3
    names_p["cassini1"] = 0.0001
    res, names, s2, _ = analyse(data, fake)
    assert s2 == ["rosetta", "tandem", "messenger"], s2
    assert res["cassini1"]["significant"] and res["cassini1"]["better"] == "de_cma"
    names_p["rosetta"] = 0.2
    res, names, s2, _ = analyse(data, fake)
    assert "rosetta" not in s2 and s2 == ["tandem", "messenger", "gtoc1"], s2
    # margin
    data["tandem"]["evals"]["jso_cma"] = [111]
    res, _, _, _ = analyse(data, fake)
    assert not res["tandem"]["within_margin"]
    data["tandem"]["evals"]["jso_cma"] = [110]
    res, _, _, _ = analyse(data, fake)
    assert res["tandem"]["within_margin"]
    # real test: inf values rank worst
    assert mwu_p([1.0, 2.0, 3.0], [math.inf, math.inf, 4.0]) < 0.5
    print("self-test ok")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv", default=os.path.join(HERE, "results", "stage1.tsv"))
    ap.add_argument("--report", default=os.path.join(HERE, "results", "report.md"))
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        self_test()
        sys.exit(0)
    data = load(a.tsv)
    res, names, stage2, _ = analyse(data)
    text = report(data, res, names, stage2)
    open(a.report, "w").write(text)
    print(text)
