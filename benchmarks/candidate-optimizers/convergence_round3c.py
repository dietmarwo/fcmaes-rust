#!/usr/bin/env python3
"""Decision of the round-3 convergence test (ROUND3C.md section 4).

Reads results/round3c/<problem>.tsv and writes results/round3c/report.md.

Usage: python3 convergence_round3c.py [--dir results/round3c] [--reps 10]
"""

import argparse
import csv
import math
import statistics
from pathlib import Path

from scipy.stats import mannwhitneyu

INCUMBENTS = ["bite", "de", "cma", "crfmnes", "da", "de_cma", "jso_cma"]
CANDIDATE = "catcmawm"
PROBLEMS = {"phased_array": 100000, "field_service": 200000, "water_network": 20000}
ALPHA = 0.05


def load(path, problem, total, reps):
    values = {s: {} for s in INCUMBENTS + [CANDIDATE]}
    violations = 0
    with open(path, newline="") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            if row["problem"] != problem or int(row["total"]) != total:
                raise SystemExit(f"{path}: unexpected row {row['problem']} {row['total']}")
            if row["root_seed"] != "5":
                raise SystemExit(f"{path}: root seed {row['root_seed']}, expected 5")
            solver = row["solver"]
            if solver not in values:
                raise SystemExit(f"{path}: unknown solver {solver}")
            rep = int(row["rep"])
            if rep in values[solver]:
                raise SystemExit(f"{path}: duplicate row {solver} rep {rep}")
            if int(row["evaluations"]) > total:
                raise SystemExit(f"{path}: {solver} rep {rep} exceeds the total")
            values[solver][rep] = float(row["best_value"])
            violations += int(row["over_budget"]) + int(row["out_of_bounds"])
    for solver, by_rep in values.items():
        if sorted(by_rep) != list(range(reps)):
            raise SystemExit(f"{path}: {solver} has repetitions {sorted(by_rep)}")
    return {s: [v[r] for r in range(reps)] for s, v in values.items()}, violations


def holm(pvalues):
    order = sorted(pvalues, key=lambda item: item[1])
    adjusted, running = {}, 0.0
    for index, (key, p) in enumerate(order):
        running = max(running, min(1.0, (len(order) - index) * p))
        adjusted[key] = running
    return adjusted


def fmt(value):
    return f"{value:.6g}"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dir", default="results/round3c")
    parser.add_argument("--reps", type=int, default=10)
    args = parser.parse_args()
    directory = Path(args.dir)

    data, tests, violations = {}, [], 0
    for problem, total in PROBLEMS.items():
        data[problem], found = load(directory / f"{problem}.tsv", problem, total, args.reps)
        violations += found
        medians = {s: statistics.median(v) for s, v in data[problem].items()}
        best = min(INCUMBENTS, key=lambda s: (medians[s], statistics.mean(data[problem][s])))
        p = mannwhitneyu(data[problem][CANDIDATE], data[problem][best],
                         alternative="two-sided").pvalue
        tests.append((problem, 1.0 if math.isnan(p) else float(p), best, medians))
    adjusted = holm([(problem, p) for problem, p, _, _ in tests])

    lines = ["# Round 3, convergence test for CatCMAwM", "",
             "Generated by `convergence_round3c.py` from the raw files of this directory "
             "under [ROUND3C.md](../../ROUND3C.md).", "",
             f"Repetitions per solver and problem: {args.reps}. Contract violations: {violations}.",
             "", "## Decision", "",
             "| Problem | Total | CatCMAwM median | Best core solver | Its median | "
             "Lower than every core solver | Adjusted p | Unadjusted p | Superior |",
             "|---|---:|---:|---|---:|:-:|---:|---:|:-:|"]
    superior_anywhere = False
    for problem, p, best, medians in tests:
        lower = all(medians[CANDIDATE] < medians[s] for s in INCUMBENTS)
        superior = lower and adjusted[problem] <= ALPHA and violations == 0
        superior_anywhere = superior_anywhere or superior
        lines.append(f"| {problem} | {PROBLEMS[problem]:,} | {fmt(medians[CANDIDATE])} | {best} | "
                     f"{fmt(medians[best])} | {'yes' if lower else 'no'} | "
                     f"{adjusted[problem]:.3g} | {p:.3g} | {'yes' if superior else 'no'} |")
    lines += ["", "**Outcome: " + ("accepted (superior on at least one problem)."
                                   if superior_anywhere else
                                   "not superior on any problem; the round-3 decision stands.")
              + "**", "", "## Medians, best and worst value per solver", ""]
    for problem in PROBLEMS:
        lines += [f"### {problem}", "", "| Solver | Median | Best | Worst |", "|---|---:|---:|---:|"]
        ranked = sorted(data[problem], key=lambda s: statistics.median(data[problem][s]))
        for solver in ranked:
            v = data[problem][solver]
            lines.append(f"| {solver} | {fmt(statistics.median(v))} | {fmt(min(v))} | {fmt(max(v))} |")
        lines.append("")
    lines += ["## Limits", "",
              f"- {args.reps} repetitions per problem, one budget each, one host.",
              "- The candidate is the Python reference implementation with default "
              "parameters, compared by evaluations.", ""]
    out = directory / "report.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}; superior on at least one problem: {superior_anywhere}")


if __name__ == "__main__":
    main()
